export function getLanguage() {
  const lang = localStorage.getItem('limra_lang');
  return lang === 'bn' ? 'bn' : 'en';
}

export function setLanguage(lang) {
  const validLang = lang === 'bn' ? 'bn' : 'en';
  localStorage.setItem('limra_lang', validLang);
  return validLang;
}

export function t(key, defaultText = '') {
  const currentLang = getLanguage();
  if (translations[currentLang] && translations[currentLang][key]) {
    return translations[currentLang][key];
  }
  if (translations['en'] && translations['en'][key]) {
    return translations['en'][key];
  }
  return defaultText || key;
}

export function translateCategory(catName) {
  const currentLang = getLanguage();
  if (currentLang === 'en') return catName;
  const key = categoryTranslations[catName] || Object.keys(categoryTranslations).find(k => catName.toLowerCase().includes(k.toLowerCase()));
  if (key && translations['bn'][categoryTranslations[key]]) {
    return translations['bn'][categoryTranslations[key]];
  }
  return catName;
}
